    // Surrogate series for randomization (permutation) tests of a backtest.
    //
    // These are batch-only generators: each one reads a whole series and writes
    // `n` randomized copies. They are not streaming operators and must not be
    // placed in a live pipeline; they exist to build a null distribution.
    //
    // Determinism: column j of the output is generated by its own generator,
    // seeded from (seed, j). The same seed therefore gives the same surrogates
    // on every platform (Python, JS/WASM, C++), and generating the columns in
    // chunks gives the same result as generating them all at once.

    // xoshiro256** (Blackman and Vigna), seeded through splitmix64. Bounded
    // integers use bitmask rejection, which is unbiased and needs no 128-bit
    // arithmetic, so the stream is identical on every compiler.
    class Rng {
    public:
        Rng(std::uint64_t seed, std::uint64_t stream) {
            std::uint64_t z = seed ^ (0x9E3779B97F4A7C15ULL * (stream + 1));
            for (auto& s : s_) s = splitmix64(z);
        }

        std::uint64_t next() {
            const std::uint64_t result = rotl(s_[1] * 5, 7) * 9;
            const std::uint64_t t = s_[1] << 17;
            s_[2] ^= s_[0]; s_[3] ^= s_[1]; s_[1] ^= s_[2]; s_[0] ^= s_[3];
            s_[2] ^= t;
            s_[3] = rotl(s_[3], 45);
            return result;
        }

        // Uniform integer in [0, n), n >= 1.
        std::uint64_t below(std::uint64_t n) {
            if (n <= 1) return 0;
            std::uint64_t mask = n - 1;
            mask |= mask >> 1; mask |= mask >> 2; mask |= mask >> 4;
            mask |= mask >> 8; mask |= mask >> 16; mask |= mask >> 32;
            std::uint64_t x;
            do { x = next() & mask; } while (x >= n);
            return x;
        }

    private:
        static std::uint64_t rotl(std::uint64_t x, int k) {
            return (x << k) | (x >> (64 - k));
        }
        static std::uint64_t splitmix64(std::uint64_t& z) {
            z += 0x9E3779B97F4A7C15ULL;
            std::uint64_t r = z;
            r = (r ^ (r >> 30)) * 0xBF58476D1CE4E5B9ULL;
            r = (r ^ (r >> 27)) * 0x94D049BB133111EBULL;
            return r ^ (r >> 31);
        }
        std::uint64_t s_[4];
    };

    namespace detail {

        // NaN-aware equality, so a run of NaN (a "hold" stretch) is one run.
        inline bool same(double a, double b) {
            return (a == b) || (std::isnan(a) && std::isnan(b));
        }

        // Index of the first non-NaN value: the warmup prefix [0, start) stays
        // in place in every surrogate.
        inline std::size_t valid_start(const double* x, std::size_t T) {
            std::size_t p = 0;
            while (p < T && std::isnan(x[p])) ++p;
            return p;
        }

        // Runs of equal value in x[p, T), as (start, length) pairs.
        inline std::vector<std::pair<std::size_t, std::size_t>>
        runs(const double* x, std::size_t p, std::size_t T) {
            std::vector<std::pair<std::size_t, std::size_t>> r;
            std::size_t i = p;
            while (i < T) {
                std::size_t j = i + 1;
                while (j < T && same(x[j], x[i])) ++j;
                r.emplace_back(i, j - i);
                i = j;
            }
            return r;
        }

    } // namespace detail

    // The default minimum shift: twice the mean run length (the mean holding
    // period, counting flat stretches as runs), at least 1, and at most a
    // quarter of the valid length. A smaller shift leaves a surrogate almost
    // aligned with the original and biases the p-value upward.
    inline std::size_t default_min_shift(const double* x, std::size_t T) {
        const std::size_t p = detail::valid_start(x, T);
        const std::size_t L = T - p;
        if (L < 4) return 1;
        const std::size_t nruns = detail::runs(x, p, T).size();
        const double mean_run = static_cast<double>(L) / static_cast<double>(nruns);
        std::size_t m = static_cast<std::size_t>(std::ceil(2.0 * mean_run));
        if (m < 1) m = 1;
        if (m > L / 4) m = L / 4 > 0 ? L / 4 : 1;
        return m;
    }

    // Circular shift: column j of `out` (row-major, shape T x ncols) is the
    // series rotated by a random offset k_j, uniform in [min_shift, L - min_shift],
    // where L is the length after the NaN warmup prefix. A rotation keeps every
    // property of the series (trade count, holding periods, long/short balance,
    // autocorrelation) and changes only its alignment with the market. Columns
    // col0 .. col0 + ncols - 1 of the full set are produced, so a caller can
    // generate the surrogates in chunks.
    //
    // `start` overrides the warmup length (the default, SIZE_MAX, uses the
    // series' own NaN prefix). Several series shifted with the same seed, start,
    // and min_shift get the same offset in every column, which is what a joint
    // test across several strategies needs.
    inline void circular_shift(const double* x, std::size_t T,
                               std::size_t min_shift, std::uint64_t seed,
                               std::size_t col0, std::size_t ncols, double* out,
                               std::size_t start = static_cast<std::size_t>(-1)) {
        const std::size_t p = start == static_cast<std::size_t>(-1)
            ? detail::valid_start(x, T) : start;
        if (p > T) throw std::invalid_argument("start is past the end of the series.");
        const std::size_t L = T - p;
        if (L < 2) throw std::invalid_argument(
            "circular_shift needs at least two values after the NaN warmup.");
        if (min_shift < 1) min_shift = 1;
        if (2 * min_shift > L) throw std::invalid_argument(
            "min_shift is too large: it must be at most half the series length "
            "after the NaN warmup.");
        const std::size_t span = L - 2 * min_shift + 1;
        // src[j] walks the source index of column j; output rows are written
        // contiguously, one row of all columns at a time.
        std::vector<std::size_t> src(ncols);
        for (std::size_t j = 0; j < ncols; ++j) {
            Rng rng(seed, col0 + j);
            const std::size_t k = min_shift + static_cast<std::size_t>(rng.below(span));
            src[j] = L - k;                       // out[p + i] = x[p + (i - k) mod L]
        }
        for (std::size_t t = 0; t < p; ++t)
            for (std::size_t j = 0; j < ncols; ++j) out[t * ncols + j] = x[t];
        for (std::size_t i = 0; i < L; ++i) {
            double* row = out + (p + i) * ncols;
            for (std::size_t j = 0; j < ncols; ++j) {
                row[j] = x[p + src[j]];
                if (++src[j] == L) src[j] = 0;
            }
        }
    }

    // Segment shuffle: split the series after its NaN warmup prefix into runs
    // of equal value (each trade, and each flat or hold stretch, is one run)
    // and write the runs back in a random order (Fisher-Yates). The multiset
    // of runs is kept exactly: the same trades, with the same sides, sizes, and
    // holding periods, at random times.
    inline void segment_shuffle(const double* x, std::size_t T, std::uint64_t seed,
                                std::size_t col0, std::size_t ncols, double* out) {
        const std::size_t p = detail::valid_start(x, T);
        const auto r = detail::runs(x, p, T);
        const std::size_t R = r.size();
        // order[j * R + i] is the i-th run written to column j. Each column then
        // keeps a cursor (current position in its order, units left in that
        // run), so output rows are written contiguously.
        std::vector<std::size_t> order(ncols * R);
        for (std::size_t j = 0; j < ncols; ++j) {
            Rng rng(seed, col0 + j);
            std::size_t* o = order.data() + j * R;
            for (std::size_t i = 0; i < R; ++i) o[i] = i;
            for (std::size_t i = R; i > 1; --i) {
                const std::size_t k = static_cast<std::size_t>(rng.below(i));
                std::swap(o[i - 1], o[k]);
            }
        }
        for (std::size_t t = 0; t < p; ++t)
            for (std::size_t j = 0; j < ncols; ++j) out[t * ncols + j] = x[t];
        if (R == 0) return;
        std::vector<std::size_t> pos(ncols, 0), left(ncols);
        for (std::size_t j = 0; j < ncols; ++j) left[j] = r[order[j * R]].second;
        for (std::size_t t = p; t < T; ++t) {
            double* row = out + t * ncols;
            for (std::size_t j = 0; j < ncols; ++j) {
                if (left[j] == 0) left[j] = r[order[j * R + (++pos[j])]].second;
                row[j] = x[r[order[j * R + pos[j]]].first];
                --left[j];
            }
        }
    }


    namespace detail {

        // Fisher-Yates shuffle of 1 .. m-1 into perm (perm[0] stays 0).
        inline void shuffle_tail(std::vector<std::size_t>& perm, Rng& rng) {
            for (std::size_t i = 0; i < perm.size(); ++i) perm[i] = i;
            for (std::size_t i = perm.size(); i > 2; --i) {
                const std::size_t k = 1 + static_cast<std::size_t>(rng.below(i - 1));
                std::swap(perm[i - 1], perm[k]);
            }
        }

        // Fisher-Yates shuffle of 0 .. m-1 into perm.
        inline void shuffle_all(std::vector<std::size_t>& perm, Rng& rng) {
            for (std::size_t i = 0; i < perm.size(); ++i) perm[i] = i;
            for (std::size_t i = perm.size(); i > 1; --i) {
                const std::size_t k = static_cast<std::size_t>(rng.below(i));
                std::swap(perm[i - 1], perm[k]);
            }
        }

    } // namespace detail

    // How a price series is taken apart before it is shuffled.
    //   Log:   log returns (relative changes); prices must be positive.
    //   Diff:  differences (absolute changes); prices may be zero or negative.
    //   Level: the values themselves; whole rows are shuffled, so there is no
    //          path to rebuild. The null for series that are stationary in
    //          level (funding rates, spreads around a fixed mean, features).
    enum class PermuteMode { Log, Diff, Level };

    inline PermuteMode parse_permute_mode(const std::string& m) {
        if (m == "log") return PermuteMode::Log;
        if (m == "diff") return PermuteMode::Diff;
        if (m == "level") return PermuteMode::Level;
        throw std::invalid_argument("mode must be \"log\", \"diff\", or \"level\".");
    }

    // Bar permutation for OHLC data (Masters 2020), with an optional volume
    // column. In Log and Diff mode each bar t >= 1 splits into a gap (open[t]
    // against close[t-1]) and an intrabar shape (high, low, and close against
    // open[t]), as log ratios or as differences. The gaps and the shapes are
    // shuffled with two independent permutations and the path is rebuilt from
    // the first bar, which stays as it is. Every surrogate keeps the first bar,
    // the last close, the distributions of gaps and shapes, and valid bars
    // (low <= open, close <= high); it has no serial structure left. In Level
    // mode whole bars are shuffled, the first one included.
    //
    // Outputs are row-major (T x ncols): the four price arrays and `source`,
    // the bar whose shape row t received (the bar itself in Level mode), so
    // that other per-bar columns can move with their bar. With a volume column
    // (`vol` not null) `ov` receives the moved volume: with `notional` false it
    // is the source bar's volume; with `notional` true it is rescaled so the
    // traded amount, volume times the typical price (high + low + close) / 3,
    // stays that of the source bar: if the price doubles, the volume halves.
    inline void permute_bars(const double* o, const double* h, const double* l,
                             const double* c, std::size_t T, PermuteMode mode,
                             std::uint64_t seed, std::size_t col0, std::size_t ncols,
                             double* oo, double* oh, double* ol, double* oc,
                             double* source,
                             const double* vol = nullptr, bool notional = false,
                             double* ov = nullptr) {
        if (T < 2) throw std::invalid_argument("permute_bars needs at least two bars.");
        const bool log = mode == PermuteMode::Log;
        for (std::size_t t = 0; t < T; ++t) {
            if (!std::isfinite(o[t] + h[t] + l[t] + c[t]))
                throw std::invalid_argument(
                    "permute_bars needs finite open, high, low, and close prices.");
            if ((log || (notional && vol)) &&
                !(o[t] > 0.0 && h[t] > 0.0 && l[t] > 0.0 && c[t] > 0.0))
                throw std::invalid_argument(log
                    ? "permute_bars with mode=\"log\" needs positive prices; use mode=\"diff\"."
                    : "volume_mode=\"notional\" needs positive prices.");
        }
        auto typical = [](double hh, double ll, double cc) { return (hh + ll + cc) / 3.0; };

        if (mode == PermuteMode::Level) {
            std::vector<std::size_t> rows(T);
            for (std::size_t j = 0; j < ncols; ++j) {
                Rng rng(seed, col0 + j);
                detail::shuffle_all(rows, rng);
                for (std::size_t t = 0; t < T; ++t) {
                    const std::size_t s = rows[t], r = t * ncols + j;
                    oo[r] = o[s]; oh[r] = h[s]; ol[r] = l[s]; oc[r] = c[s];
                    source[r] = static_cast<double>(s);
                    if (vol) ov[r] = vol[s];          // the bar moves whole: same amount
                }
            }
            return;
        }

        auto fwd = [log](double x) { return log ? std::log(x) : x; };
        auto inv = [log](double x) { return log ? std::exp(x) : x; };
        std::vector<double> gap(T), dh(T), dl(T), dc(T);
        for (std::size_t t = 1; t < T; ++t) {
            gap[t] = fwd(o[t]) - fwd(c[t - 1]);
            const double lo = fwd(o[t]);
            dh[t] = fwd(h[t]) - lo;
            dl[t] = fwd(l[t]) - lo;
            dc[t] = fwd(c[t]) - lo;
        }
        std::vector<std::size_t> shape(T), gaps(T);
        for (std::size_t j = 0; j < ncols; ++j) {
            Rng rng(seed, col0 + j);
            detail::shuffle_tail(shape, rng);
            detail::shuffle_tail(gaps, rng);
            oo[j] = o[0]; oh[j] = h[0]; ol[j] = l[0]; oc[j] = c[0]; source[j] = 0.0;
            if (vol) ov[j] = vol[0];
            double prev_close = fwd(c[0]);
            for (std::size_t t = 1; t < T; ++t) {
                const std::size_t s = shape[t], g = gaps[t];
                const double lo = prev_close + gap[g];
                const std::size_t r = t * ncols + j;
                oo[r] = inv(lo);
                oh[r] = inv(lo + dh[s]);
                ol[r] = inv(lo + dl[s]);
                prev_close = lo + dc[s];
                oc[r] = inv(prev_close);
                source[r] = static_cast<double>(s);
                if (vol) {
                    ov[r] = notional
                        ? vol[s] * typical(h[s], l[s], c[s]) / typical(oh[r], ol[r], oc[r])
                        : vol[s];
                }
            }
        }
    }

    // Permutation of a single price series, with an optional volume column.
    // In Log and Diff mode the steps after the NaN warmup prefix (log returns
    // or differences) are shuffled and the path is rebuilt from the first
    // valid value, so the first and last values are kept. In Level mode the
    // valid values themselves are shuffled. The warmup prefix stays in place.
    // `source` (as in permute_bars) is the index whose step or value row t
    // received. With a volume column, `ov` receives the moved volume, rescaled
    // with `notional` so that volume times price stays that of the source row.
    inline void permute_returns(const double* x, std::size_t T, PermuteMode mode,
                                std::uint64_t seed, std::size_t col0, std::size_t ncols,
                                double* out, double* source,
                                const double* vol = nullptr, bool notional = false,
                                double* ov = nullptr) {
        const std::size_t p = detail::valid_start(x, T);
        if (T - p < 2) throw std::invalid_argument(
            "permute_returns needs at least two values after the NaN warmup.");
        const bool log = mode == PermuteMode::Log;
        for (std::size_t t = p; t < T; ++t) {
            if (!std::isfinite(x[t]))
                throw std::invalid_argument("permute_returns needs finite values after the NaN warmup.");
            if ((log || (notional && vol)) && !(x[t] > 0.0))
                throw std::invalid_argument(log
                    ? "permute_returns with mode=\"log\" needs positive values; use mode=\"diff\"."
                    : "volume_mode=\"notional\" needs positive prices.");
        }
        const std::size_t L = T - p;
        std::vector<double> step(L);
        if (mode != PermuteMode::Level)
            for (std::size_t i = 1; i < L; ++i)
                step[i] = log ? std::log(x[p + i]) - std::log(x[p + i - 1])
                              : x[p + i] - x[p + i - 1];
        std::vector<std::size_t> perm(L);
        for (std::size_t j = 0; j < ncols; ++j) {
            Rng rng(seed, col0 + j);
            for (std::size_t t = 0; t < p; ++t) {
                out[t * ncols + j] = x[t];
                source[t * ncols + j] = static_cast<double>(t);
                if (vol) ov[t * ncols + j] = vol[t];
            }
            if (mode == PermuteMode::Level) {
                detail::shuffle_all(perm, rng);
                for (std::size_t i = 0; i < L; ++i) {
                    const std::size_t r = (p + i) * ncols + j, s = p + perm[i];
                    out[r] = x[s];
                    source[r] = static_cast<double>(s);
                    if (vol) ov[r] = vol[s];          // the row moves whole
                }
                continue;
            }
            detail::shuffle_tail(perm, rng);
            double level = log ? std::log(x[p]) : x[p];
            out[p * ncols + j] = x[p];
            source[p * ncols + j] = static_cast<double>(p);
            if (vol) ov[p * ncols + j] = vol[p];
            for (std::size_t i = 1; i < L; ++i) {
                level += step[perm[i]];
                const std::size_t r = (p + i) * ncols + j, s = p + perm[i];
                out[r] = log ? std::exp(level) : level;
                source[r] = static_cast<double>(s);
                if (vol) ov[r] = notional ? vol[s] * x[s] / out[r] : vol[s];
            }
        }
    }

