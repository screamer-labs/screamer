#!/usr/bin/env python3
"""Generate src/screamer/serial/op_registry.cpp: serial::make_op for every operator.

``serial::make_op(type, settings)`` (include/screamer/serial/op_registry.h)
builds an operator by name from the "settings" object of a save file. The
JavaScript loader and C++ users build through it; Python builds through its
own classes (screamer/serial.py).

The constructor of each operator comes from devtools/wasm/wasm_manifest.json:
its C++ type, the C++ types of its arguments and their names and default
literals, read from the nanobind bindings. The setting names are checked
against screamer/data/help.json, so a file names its settings as the docs do.
Each argument is read from the setting of its name:

    int                    an integer in the int range
    double                 a number
    std::optional<double>  a number, or null / missing for "not given"
    bool                   a boolean
    std::string            a string
    std::vector<double>    a number (one entry) or an array of numbers
    screamer::OpArg        a nested operator {"type": T, "settings": {...}}

A missing or null setting takes the default literal of the binding; one
without a default is required. An operator whose constructor cannot be read
this way is listed in UNBUILDABLE and raises NotSaveable.

Usage:
    python devtools/gen_op_registry.py            # write the .cpp
    python devtools/gen_op_registry.py --stdout   # print it (freshness test)
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
MANIFEST = REPO / "devtools" / "wasm" / "wasm_manifest.json"
HELP_JSON = REPO / "screamer" / "data" / "help.json"
OUT = REPO / "src" / "screamer" / "serial" / "op_registry.cpp"

sys.path.insert(0, str(REPO / "devtools" / "wasm"))
from gen_wasm_bindings import collect_op_headers  # noqa: E402

# C++ argument type -> the reader of its setting.
READERS = {
    "int": "read_int",
    "double": "read_double",
    "std::optional<double>": "read_optional",
    "bool": "read_bool",
    "std::string": "read_string",
    "std::vector<double>": "read_vector",
    "screamer::OpArg": "read_op",
}

HEADER = """\
// GENERATED by devtools/gen_op_registry.py -- do not edit by hand.
// serial::make_op for every operator of devtools/wasm/wasm_manifest.json
// (include/screamer/serial/op_registry.h).
"""

HELPERS = r"""
namespace {

using screamer::json::Value;
using screamer::serial::SaveError;

// The setting of an operator (type, its parameter `name`) in errors.
[[noreturn]] SCREAMER_NOINLINE void wrong(const char* type, const char* name, const char* expected,
                                          const Value& got) {
    throw SaveError(std::string(type) + ".settings." + name + ": expected " + expected + ", got " +
                    (got.is_number() ? screamer::json::dump(got, -1)
                                     : screamer::serial::detail::kind_text(got)));
}

[[noreturn]] SCREAMER_NOINLINE void required(const char* type, const char* name) {
    throw SaveError(std::string(type) + ".settings." + name + ": missing required parameter");
}

// The settings of `s` by the parameter `names` of the operator: v[k] is the
// value of names[k], or null when it is missing or null. A setting that is
// not a parameter raises.
SCREAMER_NOINLINE void collect(const Value& s, const char* type, const char* const* names, std::size_t n,
                               const Value** v) {
    for (std::size_t k = 0; k < n; ++k) v[k] = nullptr;
    for (const auto& kv : s.o) {
        std::size_t k = 0;
        while (k < n && kv.first != names[k]) ++k;
        if (k == n) throw SaveError(std::string(type) + ".settings." + kv.first + ": unknown parameter");
        if (kv.second.kind != Value::Kind::Null) v[k] = &kv.second;
    }
}

SCREAMER_NOINLINE int read_int(const Value& v, const char* type, const char* name) {
    if (v.kind != Value::Kind::Int || v.i < std::numeric_limits<int>::min() ||
        v.i > std::numeric_limits<int>::max())
        wrong(type, name, "an integer in the int range", v);
    return static_cast<int>(v.i);
}

SCREAMER_NOINLINE double read_double(const Value& v, const char* type, const char* name) {
    if (!v.is_number()) wrong(type, name, "a number", v);
    return v.as_double();
}

std::optional<double> read_optional(const Value& v, const char* type, const char* name) {
    return read_double(v, type, name);
}

SCREAMER_NOINLINE bool read_bool(const Value& v, const char* type, const char* name) {
    if (v.kind != Value::Kind::Bool) wrong(type, name, "a boolean", v);
    return v.b;
}

SCREAMER_NOINLINE std::string read_string(const Value& v, const char* type, const char* name) {
    if (v.kind != Value::Kind::String) wrong(type, name, "a string", v);
    return v.s;
}

// A number is the one-entry vector (one value for every asset).
SCREAMER_NOINLINE std::vector<double> read_vector(const Value& v, const char* type, const char* name) {
    if (v.is_number()) return {v.as_double()};
    if (v.kind != Value::Kind::Array) wrong(type, name, "a number or an array of numbers", v);
    std::vector<double> r;
    r.reserve(v.a.size());
    for (const Value& x : v.a) {
        if (!x.is_number()) wrong(type, name, "a number or an array of numbers", x);
        r.push_back(x.as_double());
    }
    return r;
}

SCREAMER_NOINLINE screamer::OpArg read_op(const Value& v, const char* type, const char* name) {
    const std::string where = std::string(type) + ".settings." + name;
    const Value* t = v.kind == Value::Kind::Object ? v.get("type") : nullptr;
    const Value* settings = v.kind == Value::Kind::Object ? v.get("settings") : nullptr;
    if (!t || !settings || v.o.size() != 2 || t->kind != Value::Kind::String)
        throw SaveError(where + ": expected {\"type\": ..., \"settings\": {...}}");
    return screamer::OpArg::owning(screamer::serial::make_op(t->s, *settings, where));
}

using Maker = std::unique_ptr<screamer::EvalOp> (*)(const Value&);
"""[1:]


def load_ops() -> list[dict]:
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def load_help() -> dict:
    return json.loads(HELP_JSON.read_text(encoding="utf-8"))


def buildable(op: dict, help_map: dict) -> str | None:
    """None when make_op can build ``op``, else why not."""
    if len(op.get("ctor_args") or []) != len(op["ctor"]):
        return "the binding's argument names do not match its constructor"
    for t in op["ctor"]:
        if t not in READERS:
            return f"no reader for the C++ type {t}"
    names = [a["name"] for a in op["ctor_args"]]
    doc = [p["name"] for p in (help_map.get(op["name"]) or {}).get("parameters") or []]
    if sorted(names) != sorted(doc):
        return f"the constructor's names {names} are not help.json's {doc}"
    return None


def render_arg(op: dict, i: int) -> str:
    t = op["ctor"][i]
    a = op["ctor_args"][i]
    default = a["default"]
    got = f'{READERS[t]}(*v[{i}], T, N[{i}])'
    if t == "std::optional<double>":
        fallback = "std::optional<double>()"
    elif default is None:
        fallback = f"(required(T, N[{i}]), {t}())"
    else:
        fallback = default
        if t == "std::vector<double>":
            # The default may be a PerAsset, which converts to and from a vector.
            got = f"decltype({default})({got})"
    return f"v[{i}] ? {got} : {fallback}"


def render_maker(op: dict) -> str:
    name = op["name"]
    n = len(op["ctor"])
    lines = [f"std::unique_ptr<screamer::EvalOp> make_{name}(const Value& s) {{"]
    lines.append(f'    static const char* const T = "{name}";')
    if n == 0:
        lines.append("    collect(s, T, nullptr, 0, nullptr);")
        lines.append(f"    return std::make_unique<{op['cpp_type']}>();")
    else:
        names = ", ".join(f'"{a["name"]}"' for a in op["ctor_args"])
        lines.append(f"    static const char* const N[] = {{{names}}};")
        lines.append(f"    const Value* v[{n}];")
        lines.append(f"    collect(s, T, N, {n}, v);")
        args = ",\n        ".join(render_arg(op, i) for i in range(n))
        lines.append(f"    return std::make_unique<{op['cpp_type']}>(\n        {args});")
    lines.append("}")
    return "\n".join(lines)


def generate(ops: list[dict], help_map: dict) -> str:
    ok = [op for op in ops if buildable(op, help_map) is None]
    skipped = [(op["name"], buildable(op, help_map)) for op in ops if buildable(op, help_map)]
    out = [HEADER]
    out.append('#include "screamer/serial/op_registry.h"')
    out.append("")
    for h in ["algorithm", "cstddef", "initializer_list", "limits", "memory", "optional",
              "string", "utility", "vector"]:
        out.append(f"#include <{h}>")
    out.append("")
    out.append('#include "screamer/common/eval_op.h"   // SCREAMER_NOINLINE')
    out.append('#include "screamer/common/json.h"')
    out.append('#include "screamer/common/op_arg.h"')
    out.append('#include "screamer/serial/errors.h"')
    out.append('#include "screamer/serial/settings_compat.h"')
    for h in collect_op_headers():
        out.append(f'#include "{h}"')
    out.append("")
    out.append(HELPERS)
    for op in ok:
        out.append(render_maker(op))
        out.append("")
    out.append("// The makers, sorted by name for the binary search in make_op.")
    out.append("struct Entry {")
    out.append("    const char* name;")
    out.append("    Maker make;")
    out.append("};")
    out.append("")
    out.append("const Entry kRegistry[] = {")
    for op in sorted(ok, key=lambda o: o["name"]):
        out.append(f'    {{"{op["name"]}", &make_{op["name"]}}},')
    out.append("};")
    out.append("")
    out.append("const Entry* find(const std::string& type) {")
    out.append("    const Entry* end = std::end(kRegistry);")
    out.append("    const Entry* e = std::lower_bound(std::begin(kRegistry), end, type,")
    out.append("        [](const Entry& x, const std::string& t) { return t.compare(x.name) > 0; });")
    out.append("    return e != end && type == e->name ? e : nullptr;")
    out.append("}")
    out.append("")
    out.append("// Operators make_op cannot build, and why: they raise NotSaveable.")
    out.append("const char* const kUnbuildable[][2] = {")
    for name, why in skipped:
        out.append(f'    {{"{name}", "{why}"}},')
    out.append('    {nullptr, nullptr},')
    out.append("};")
    out.append("")
    out.append("}  // namespace")
    out.append("")
    out.append(MAKE_OP)
    return "\n".join(out)


MAKE_OP = r"""
namespace screamer { namespace serial {

std::unique_ptr<EvalOp> make_op(const std::string& type, const json::Value& settings,
                                 const std::string& path) {
    const Entry* e = find(type);
    if (!e) {
        for (auto* u = kUnbuildable; (*u)[0]; ++u)
            if (type == (*u)[0]) throw NotSaveable(type, (*u)[1]);
        throw SaveError(path + ".type: unknown type '" + type + "'");
    }
    if (settings.kind != json::Value::Kind::Object)
        throw SaveError(type + ".settings: expected an object, got " + detail::kind_text(settings));
    json::Value s = settings;
    apply_settings_compat(type, s, type);
    try {
        return e->make(s);
    } catch (const SaveError&) {
        throw;
    } catch (const std::invalid_argument& err) {
        throw SaveError(type + ".settings: " + err.what());
    }
}

std::vector<std::string> registry_types() {
    std::vector<std::string> names;
    for (const Entry& e : kRegistry) names.emplace_back(e.name);
    return names;
}

}}  // namespace screamer::serial
"""[1:]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--stdout", action="store_true", help="print the output instead of writing it")
    args = ap.parse_args()
    text = generate(load_ops(), load_help())
    if args.stdout:
        sys.stdout.write(text)
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
