#!/usr/bin/env python3
"""Build the "What you can build" page and the home page tiles.

Reads ``docs/examples.yml``, which lists every recipe and notebook grouped by
task, and writes:

- ``docs/capabilities.md``: one section per area, with its intro, the functions
  to start with, longer guides, and a thumbnail card for each example.
- ``docs/examples_tiles.inc``: the home page's thumbnail tiles, one per area,
  each linking to its section.

Card titles are the examples' own page titles, and thumbnails come from
``devtools/build_gallery.py``. The build fails when a listed page, link, or
thumbnail does not exist, or when a recipe or notebook is not listed.

Run after changing docs/examples.yml or adding an example, and commit the result:

    poetry run python devtools/build_examples.py

``--check`` writes nothing and exits 1 when a generated file is stale.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
SPEC = DOCS / "examples.yml"
PAGE = DOCS / "capabilities.md"
TILES = DOCS / "examples_tiles.inc"
GALLERY = DOCS / "_static" / "gallery"

TITLE_RE = re.compile(r"^# (.+)$", re.M)
LINK_RE = re.compile(r"\]\(([^)#\s]+)(?:#[^)]*)?\)")
KIND = {"recipes": "Recipe", "notebooks": "Notebook"}


def example_docs() -> set[str]:
    """Every recipe and notebook page, as a doc path without suffix."""
    recipes = {f"recipes/{p.stem}" for p in (DOCS / "recipes").glob("*.md")
               if p.stem != "index"}
    notebooks = {f"notebooks/{p.stem}" for p in (DOCS / "notebooks").glob("*.ipynb")}
    return recipes | notebooks


def page_title(doc: str) -> str:
    md = DOCS / f"{doc}.md"
    if md.exists():
        text = md.read_text()
    else:
        nb = json.loads((DOCS / f"{doc}.ipynb").read_text())
        text = "\n".join("".join(c["source"]) for c in nb["cells"]
                         if c["cell_type"] == "markdown")
    m = TITLE_RE.search(text)
    if not m:
        raise SystemExit(f"{doc}: no '# Title' heading")
    return m.group(1).strip()


def check_links(where: str, text: str) -> None:
    for target in LINK_RE.findall(text):
        if "://" not in target and not (DOCS / target).exists():
            raise SystemExit(f"examples.yml, {where}: link target {target} does not exist")


def thumb(doc: str) -> str:
    name = doc.replace("/", "__") + ".webp"
    if not (GALLERY / name).exists():
        raise SystemExit(f"{doc}: no thumbnail {name}; run devtools/build_gallery.py")
    return name


def build() -> dict[Path, str]:
    spec = yaml.safe_load(SPEC.read_text())
    areas = spec["areas"]

    listed = [ex["doc"] for a in areas for ex in a["examples"]]
    missing = sorted(example_docs() - set(listed))
    unknown = sorted(set(listed) - example_docs())
    if missing or unknown:
        raise SystemExit(f"examples.yml: not listed {missing}, no such page {unknown}")

    page = [
        "<!-- Generated by devtools/build_examples.py from docs/examples.yml.",
        "     Do not edit by hand. -->",
        "",
        "# What you can build",
        "",
        "Worked examples, grouped by task. Recipes are short and solve one task; most",
        "run on real market data committed with the docs: six hours of Deribit BTC and",
        "ETH perpetual trades, daily Binance bars of 20 coins from 2022 to 2026, and the",
        "BTC perpetual's funding rates. Notebooks tour one area in depth. Every example",
        "runs when the docs build. The [gallery](gallery.rst) shows a plot for every",
        "function.",
        "",
    ]
    tiles = [
        ".. Generated by devtools/build_examples.py from docs/examples.yml.",
        ".. Do not edit by hand.",
        "",
        ".. grid:: 1 2 3 3",
        "   :gutter: 3",
        "",
    ]
    for a in areas:
        for key in ("intro", "functions", "guides"):
            check_links(f"{a['slug']}.{key}", a.get(key, ""))
        if not (GALLERY / a["image"]).exists():
            raise SystemExit(f"examples.yml, {a['slug']}: no thumbnail {a['image']}")

        page += [f"(area-{a['slug']})=", f"## {a['title']}", "", a["intro"], ""]
        if a.get("functions"):
            page += [f"Functions: {a['functions']}", ""]
        if a.get("guides"):
            page += [f"Guides: {a['guides']}", ""]
        if a["examples"]:
            page += ["```{grid} 1 2 2 3", ":gutter: 3", ""]
            for ex in a["examples"]:
                doc = ex["doc"]
                title = page_title(doc)
                check_links(doc, ex["text"])
                page += [
                    f":::{{grid-item-card}} {title}",
                    f":link: {doc}",
                    ":link-type: doc",
                    f":img-top: _static/gallery/{thumb(doc)}",
                    f":img-alt: {title}",
                    ex["text"],
                    "+++",
                    KIND[doc.split("/")[0]],
                    ":::",
                    "",
                ]
            page += ["```", ""]

        tiles += [
            f"   .. grid-item-card:: {a['title']}",
            f"      :img-top: _static/gallery/{a['image']}",
            f"      :img-alt: {a['alt']}",
            f"      :link: area-{a['slug']}",
            "      :link-type: ref",
            "",
            f"      {a['tile']}",
            "",
        ]

    skip = set(spec.get("not_in_toctree", []))
    page += ["```{toctree}", ":hidden:", ""]
    page += [d for d in dict.fromkeys(listed) if d not in skip]
    page += ["```"]
    return {PAGE: "\n".join(page) + "\n", TILES: "\n".join(tiles).rstrip() + "\n"}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="write nothing; exit 1 when a generated file is stale")
    args = ap.parse_args(argv)
    stale = []
    for path, text in build().items():
        if path.exists() and path.read_text() == text:
            continue
        stale.append(path)
        if not args.check:
            path.write_text(text)
    for path in stale:
        verb = "stale" if args.check else "wrote"
        print(f"{verb}: {path.relative_to(ROOT)}")
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
